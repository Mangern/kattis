const int mxN = 1e6+6;
const ll MOD  = 1e9+7;

struct Edge {
    int u;
    int v;
    ll s, t;
    ld p;
    int ridx;

    bool operator<(const Edge& other) const {
        if (s == other.s) {
            return make_tuple(u, v, p) < make_tuple(other.u, other.v, p);
        }
        return s < other.s;
    }
};

int n, m;
ll Tend;
ld dp[mxN];
Edge edges[mxN];
vector<int> adj[mxN];
int par[mxN];

int find_next_ei(int u, ll t) {
    auto it = upper_bound(all(adj[u]), t, 
        [&](auto t, auto j) { return t < edges[j].s; });
    if (it == end(adj[u])) {
        return -1;
    }
    return *it;
}

ld solve(int ei) {
    ei = par[ei];
    if (dp[ei] >= 0.0) {
        return dp[ei];
    }
    ld &r = dp[ei];
    Edge ed = edges[ei];
    r = 0.0;

    int last;
    for (last = ed.ridx; last < adj[ed.u].size(); ++last) {
        if (edges[adj[ed.u][last]].s != ed.s) break;
    }
    // probability of winning if we wait at this time
    ld p_rest = last < adj[ed.u].size() ? solve(adj[ed.u][last]) : 0.0;

    r = p_rest;

    for (int i = ed.ridx; i < last; ++i) {
        Edge here = edges[adj[ed.u][i]];

        if (here.v == 1) {
            r = max(r, (ld)here.p + (ld)(1.0 - here.p) * p_rest);
        } else {
            int nei = find_next_ei(here.v, here.t);
            if (nei != -1) {
                r = max(r, (ld)here.p * solve(nei) + (ld)(1.0 - here.p) * p_rest);
            }
        }
    }
    return r;
}

void testCase() {
    cin >> m >> n;
    cin >> Tend;

    for (int i = 0; i < m; ++i) {
        dp[i] = -1.0;

        int u, v;
        ll s, t;
        ld p;
        cin >> u >> v >> s >> t >> p;
        edges[i] = {.u = u, .v = v, .s = s, .t = t, .p = p, .ridx = (int)adj[u].size()};
        adj[u].push_back(i);
    }

    for (int u = 0; u < n; ++u) {
        sort(all(adj[u]), [&](auto i, auto j) { return edges[i] < edges[j]; });

        for (int i = 0; i < adj[u].size(); ++i) {
            edges[adj[u][i]].ridx = i;
            if (i == 0 || edges[adj[u][i-1]].s != edges[adj[u][i]].s) {
                par[adj[u][i]] = adj[u][i];
            } else {
                par[adj[u][i]] = par[adj[u][i-1]];
            }
        }
    }
    if (adj[0].empty()) {
        cout << 0.0 << endl;
        return;
    }
    ld ans = 0.0;
    for (int ei : adj[0]) {
        ans = max(ans, solve(ei));
    }
    cout << setprecision(9) << fixed << ans << endl;
}

